/** Тестийн хариунаас гарсан оноонд тулгуурласан, болгоомжтой тайлбар. */
export function getUserScoreContext(percentage: number): string {
  if (percentage >= 75) {
    return "Таны 3 асуултын хариу энэ чиглэлд өндөр гэж үнэлэгдсэн. Ийм төрлийн үйл ажиллагаа танд ойлгомжтой, хэрэгтэй мэт санагддаг гэж хариулсан.";
  }
  if (percentage >= 50) {
    return "Таны хариу дунд түвшинтэй. Зарим тал нь тохирч байгаа, зарим нь тодорхой биш гэж үзсэн.";
  }
  if (percentage >= 25) {
    return "Таны хариу харьцангуй бага. Энэ чиглэл одоогоор бага чухал эсвэл сул мэт санагддаг гэж тэмдэглэсэн.";
  }
  return "Таны хариу маш бага. Энэ чиглэлд өөртөө итгэл бага гэж хариулсан (3 асуулиар л тодорхойлох боломжгүй).";
}
